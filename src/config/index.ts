import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);

// ===========================================================================
// Версия сервиса
// ===========================================================================

/**
 * Версия сервиса.
 *
 * Читается из package.json, а не из npm_package_version: переменная
 * заполняется только при запуске через npm/pnpm-скрипт, а при прямом
 * `node dist/nest/main.js` (так работает CMD в Dockerfile) в окружении
 * может оказаться значение от постороннего пакета.
 */
export const CONVERTER_VERSION: string = (() => {
  try {
    const pkg = require('../../package.json') as { version?: string };
    return pkg.version ?? '0.0.0';
  } catch {
    return '0.0.0';
  }
})();

