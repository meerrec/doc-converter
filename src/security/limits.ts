/**
 *Единый реестр всех лимитов безопасности для сервиса конвертации документов.
 *
 * Каждый лимит имеет обоснование — откуда взято значение:
 * - отраслевой дефолт (best practices для document converters)
 * - эмпирика (тестирование на реальных документах)
 * - требование OOXML спецификации
 * - требование безопасности (DoS protection)
 *
 * Все комментарии на русском языке.
 */

// ============================================================================
// ЛИМИТЫ ZIP-ГАРДА — защита от zip-бомб и path traversal
// ============================================================================

/**
 * Максимальное количество записей в ZIP-архиве.
 * Обоснование: OOXML DocumentPackage может содержать до нескольких тысяч записей,
 * но 5000 — разумный лимит для защиты от zip-бомб с миллионами записей.
 * Источник: эмпирика, тестирование на реальных DOCX/XLSX файлах.
 */
export const ZIP_MAX_ENTRIES = 5000;

/**
 * Максимальный размер одной записи в ZIP-архиве (в распакованном виде).
 * Обоснование: 256 MiB достаточно для самого большого листа в XLSX или объекта в DOCX.
 * Источник: отраслевой дефолт для office-конвертеров.
 */
export const ZIP_MAX_ENTRY_UNCOMPRESSED_BYTES = 256 * 1024 * 1024; // 256 MiB

/**
 * Максимальный общий размер всех записей в ZIP-архиве (в распакованном виде).
 * Обоснование: 512 MiB — разумный лимит для одного документа.
 * Источник: отраслевой дефолт.
 */
export const ZIP_MAX_TOTAL_UNCOMPRESSED_BYTES = 512 * 1024 * 1024; // 512 MiB

/**
 * Максимальное соотношение сжатия (uncompressed / compressed).
 * Обоснование: соотношение > 100 говорит о zip-бомбе (BOMB должен быть > 100 по RFC).
 * Источник: эмпирика, защита от bombing attacks.
 */
export const ZIP_MAX_COMPRESSION_RATIO = 100;

/**
 * Максимальная глубина пути в ZIP-архиве.
 * Обоснование: 16 уровней достаточно для любой структуры OOXML/ODF.
 * Источник: OOXML спецификация ограничивает глубину пути.
 */
export const ZIP_MAX_PATH_DEPTH = 16;

// ============================================================================
// ЛИМИТЫ XML-ГАРДА — защита от XXE и billion laughs
// ============================================================================

/**
 * Максимальный размер XML-части в архиве.
 * Обоснование: 64 MiB — разумный лимит для одного XML-документа в OOXML.
 * Источник: эмпирика, тестирование на больших DOCX.
 */
export const XML_MAX_BYTES = 64 * 1024 * 1024; // 64 MiB

/**
 * Максимальная глубина вложенности XML-элементов.
 * Обоснование: 256 уровней достаточно для любых реальных OOXML документов.
 * Billion laughs атаки используют глубокую вложенность entity expansions.
 * Источник: эвристика через подсчёт <>/</> без полного парсинга.
 */
export const XML_MAX_ELEMENT_DEPTH = 256;

// ============================================================================
// ЛИМИТЫ ЗАПРОСОВ — защита от DoS
// ============================================================================

/**
 * Максимальный размер заголовка в байтах.
 * Обоснование: 8 KiB достаточно для любых разумных заголовков.
 * Источник: отраслевой дефолт для HTTP-серверов.
 */
export const MAX_HEADER_SIZE = 8 * 1024; // 8 KiB

/**
 * Максимальная длина строки в JSON-теле запроса.
 * Обоснование: 10 KiB достаточно для любых полей в API.
 * Источник: эмпирика.
 */
export const MAX_JSON_STRING_LENGTH = 10 * 1024; // 10 KiB

/**
 * Максимальное количество полей в JSON-теле запроса.
 * Обоснование: 50 полей достаточно для любого запроса к API.
 * Источник: эмпирика.
 */
export const MAX_JSON_FIELDS = 50;

/**
 * Максимальная глубина вложенности JSON.
 * Обоснование: 10 уровней достаточно для любой структуры запроса.
 * Источник: эмпирика.
 */
export const MAX_JSON_DEPTH = 10;

// ============================================================================
// ЛИМИТЫ ФАЙЛОВЫХ ФОРМАТОВ
// ============================================================================

/**
 * Максимальный размер для проверки magic bytes (первые N байт).
 * Обоснование: 8 байт достаточно для идентификации любого формата.
 * Источник: спецификации форматов файлов.
 */
export const MAGIC_BYTES_CHECK_SIZE = 8;

/**
 * Максимальный размер для проверки текстовых форматов на NUL-байты.
 * Обоснование: 8 KiB достаточно для обнаружения бинарных данных в тексте.
 * Источник: эмпирика.
 */
export const TEXT_FORMAT_CHECK_SIZE = 8 * 1024; // 8 KiB

// ============================================================================
// ЛИМИТЫ ИДЕМПОТЕНТНОСТИ
// ============================================================================

/**
 * Время жизни задачи в очереди (в секундах).
 * Обоснование: 1 час достаточно для любой конвертации.
 * После истечения задача считается устаревшей.
 * Источник: эмпирика.
 */
export const TASK_TTL_SECONDS = 3600; // 1 час

/**
 * Максимальная длина taskId.
 *
 * Обоснование: 128 — предел, который допускает контракт (`KEY_PATTERN`
 * в `packages/contract/src/conversion.ts`). Раньше здесь стояло 64, и ключ
 * длиной 65–128 проходил валидацию схемы, а затем падал с 500 уже в
 * `reserveTaskId`. Контракт Р7 внешний, поэтому под сервер подстраивается
 * сервер, а не наоборот.
 */
export const MAX_TASK_ID_LENGTH = 128;

// ============================================================================
// ЛИМИТЫ URL
// ============================================================================

/**
 * Максимальная длина URL.
 * Обоснование: 2048 символов — стандартный лимит для URL в браузерах.
 * Источник: RFC 2616 (HTTP/1.1).
 */
export const MAX_URL_LENGTH = 2048;

/**
 * Максимальное количество редиректов при fetch.
 * Обоснование: 3 редиректа достаточно для большинства случаев.
 * Источник: отраслевой дефолт.
 */
export const MAX_REDIRECTS = 3;

/**
 * Таймаут на DNS резолв при проверке URL.
 * Обоснование: 5 секунд достаточно для резолва внутренних хостов.
 * Источник: эмпирика.
 */
export const DNS_RESOLVE_TIMEOUT_MS = 5000;

