/**
 * Лимиты безопасности сервиса.
 *
 * Набор урезан вместе с переходом на конвертацию XLSX → PDF: лимиты XML,
 * URL и идемпотентности относились к удалённым путям (XML-бомбы, загрузка
 * по ссылке, ключи Р7-Офис). Осталось то, что защищает текущий вход:
 * zip-контейнер XLSX и сигнатуры файлов.
 *
 * Все комментарии на русском языке.
 */

// ============================================================================
// ЛИМИТЫ ZIP-ГАРДА — защита от zip-бомб и path traversal
// ============================================================================

/**
 * Максимальное количество записей в ZIP-архиве.
 *
 * Обоснование: книга XLSX содержит несколько сотен записей (листы, стили,
 * общие строки), 5000 — заведомо больше любой реальной книги и при этом
 * отсекает бомбы с миллионами записей.
 * Источник: эмпирика на реальных XLSX.
 */
export const ZIP_MAX_ENTRIES = 5000;

/**
 * Максимальный размер одной записи в распакованном виде.
 *
 * Обоснование: 256 МиБ — потолок для самого большого листа книги, который
 * сервис вообще принимает (вход ограничен 100 МиБ сжатых данных).
 * Источник: отраслевой дефолт для офисных конвертеров.
 */
export const ZIP_MAX_ENTRY_UNCOMPRESSED_BYTES = 256 * 1024 * 1024;

/**
 * Максимальный суммарный размер всех записей в распакованном виде.
 *
 * Обоснование: 512 МиБ — распакованная книга, которая ещё открывается
 * в LibreOffice, не превышая память реплики.
 * Источник: отраслевой дефолт.
 */
export const ZIP_MAX_TOTAL_UNCOMPRESSED_BYTES = 512 * 1024 * 1024;

/**
 * Максимальное соотношение сжатия (uncompressed / compressed).
 *
 * Обоснование: соотношение выше 100 — признак zip-бомбы; легитимные XLSX
 * дают соотношение порядка 10–20 (XML хорошо сжимается, но не в сто раз).
 * Источник: эмпирика, защита от bombing-атак.
 */
export const ZIP_MAX_COMPRESSION_RATIO = 100;

/**
 * Максимальная глубина пути в ZIP-архиве.
 *
 * Обоснование: структура XLSX плоская (`xl/worksheets/sheet1.xml` — три
 * уровня); 16 уровней отсекают попытки утопить файл в глубокой вложенности.
 * Источник: OOXML-спецификация ограничивает глубину пути.
 */
export const ZIP_MAX_PATH_DEPTH = 16;

// ============================================================================
// ЛИМИТЫ ФАЙЛОВЫХ ФОРМАТОВ
// ============================================================================

/**
 * Сколько байт файла нужно для проверки сигнатуры.
 *
 * Обоснование: 8 байт — длина самой длинной сигнатуры среди поддерживаемых
 * (OLE-заголовок `.xls`).
 * Источник: спецификации форматов.
 */
export const MAGIC_BYTES_CHECK_SIZE = 8;

// ============================================================================
// ЭКСПОРТ ВСЕХ ЛИМИТОВ ДЛЯ УДОБСТВА ИМПОРТА
// ============================================================================

export const LIMITS = {
  ZIP_MAX_ENTRIES,
  ZIP_MAX_ENTRY_UNCOMPRESSED_BYTES,
  ZIP_MAX_TOTAL_UNCOMPRESSED_BYTES,
  ZIP_MAX_COMPRESSION_RATIO,
  ZIP_MAX_PATH_DEPTH,
  MAGIC_BYTES_CHECK_SIZE,
};
