export const DEFAULT_CONVERSION_OPTIONS: ConversionOptions = {
  watermark: '',
  watermarkMode: 'single',
  fitToOnePage: true,
  pdfVersion: 'default',
  quality: 90,
  reduceImageResolution: true,
  maxImageResolution: 300,
  exportBookmarks: true,
  taggedPdf: false,
  userPassword: '',
  ownerPassword: '',
  restrictPermissions: false,
  allowPrinting: true,
  allowChanges: false,
};

/** Предельная длина текста водяного знака — ограничение серверной схемы. */
export const MAX_WATERMARK_LENGTH = 200;

/**
 * Базовый интервал опроса одной задачи (мс).
 *
 * Обоснование: контракт не отдаёт прогресс в процентах, поэтому о завершении
 * узнаётся только опросом. Секунда — нижняя граница разумного: конвертация
 * занимает секунды и минуты, а чаще спрашивать одну задачу бессмысленно
 * (требование «не чаще одного запроса в секунду на задачу»).
 */
export const POLL_INTERVAL_MS = 1000;

/**
 * Максимальный интервал опроса при сбоях (мс).
 *
 * Обоснование: 10 секунд — пауза, после которой задача всё равно не может
 * завершиться незаметно: при недоступном API интерфейс не должен долбить
 * сервер запросами, но и не должен «замирать» на минуты.
 */
export const POLL_MAX_INTERVAL_MS = 10_000;

/**
 * Предельное время ожидания одной задачи (мс).
 *
 * Обоснование: конвертация ограничена `CONVERSION_TIMEOUT_MS` (120 с,
 * `src/config/index.ts`), но до неё задача может стоять в очереди своего
 * уровня за другими файлами. Пятнадцать минут — запас и на очередь,
 * и на повторы; статус задачи сервер хранит 24 часа, поэтому дедлайн
 * защищает интерфейс от «вечного» ожидания, а не от потери результата.
 */
export const POLL_DEADLINE_MS = 15 * 60 * 1000;

/**
 * Сколько файлов отправляется одновременно.
 *
 * Обоснование: ограничитель сервера — ведро с токенами, ёмкость `RATE_BURST`
 * (20 запросов), пополнение `RATE_PER_SEC` (5 в секунду). Две одновременные
 * отправки с интервалом 400 мс дают 2,5 запроса в секунду; опрос статусов
 * добавляет не больше 3,3 (см. `STATUS_MIN_INTERVAL_MS`) — итого около 5,8
 * в секунду на пересечении отправок и опроса. Всплеск в 20 запросов его
 * покрывает, а после завершения отправок остаётся только опрос, который
 * в устойчивом режиме идёт медленнее пополнения.
 *
 * Если `RATE_PER_SEC` будет понижен, эти значения придётся пересчитать.
 */
export const BATCH_CONCURRENCY = 2;

/** Минимальная пауза между запусками отправок (мс). */
export const BATCH_MIN_INTERVAL_MS = 400;

/**
 * Сколько запросов статуса выполняется одновременно.
 *
 * Обоснование: 2 — тот же порядок, что и у отправки. Больше не нужно:
 * запрос статуса дешёвый, а его вклад в общий лимит частоты регулируется
 * не параллелизмом, а паузой между запусками.
 */
export const STATUS_CONCURRENCY = 2;

/**
 * Минимальная пауза между запросами статуса (мс).
 *
 * Обоснование: запросы статуса идут по одному на задачу (батча в новом API
 * нет), поэтому без общей паузы число запросов росло бы вместе с числом
 * активных задач и упиралось в `RATE_PER_SEC`. Пауза 300 мс ограничивает
 * поток сверху 3,3 запроса в секунду независимо от размера пакета.
 */
export const STATUS_MIN_INTERVAL_MS = 300;
