/**
 * Настройки веб-интерфейса.
 *
 * Здесь остались только параметры самого клиента — размеры загрузки и ритм
 * опроса. Всё, что описывает контракт с сервером (форматы, кодировки,
 * разделители, коды ошибок), живёт в `@doc-converter/contract`: раньше эти
 * списки были продублированы здесь и расходились с серверными.
 *
 * Значения встраиваются в сборку, менять их переменными окружения контейнера
 * бессмысленно.
 */

/**
 * Предельный размер загружаемого файла (30 МиБ).
 *
 * Обоснование: сервер принимает тело до 50 МиБ (nginx `client_max_body_size`,
 * express.json на маршруте конвертации), а base64 увеличивает объём примерно
 * на треть — то есть потолок около 37,5 МиБ исходного файла. 30 МиБ оставляют
 * запас и дают внятное сообщение вместо ошибки 413 от body-parser.
 */
export const MAX_UPLOAD_BYTES = 30 * 1024 * 1024;

/** Базовый интервал опроса статусов (мс). */
export const POLL_INTERVAL_MS = 1500;

/**
 * Максимальный интервал опроса при замедлении (мс).
 *
 * Обоснование: 10 секунд — в замедленном режиме задача всё равно не может
 * завершиться быстрее, чем за это время (сервер отводит на конвертацию 60 с),
 * а сервер перестаёт получать запросы чаще, чем нужно. Раньше было 5 секунд.
 */
export const POLL_MAX_INTERVAL_MS = 10000;

/**
 * Предельное время ожидания задачи (мс).
 *
 * Обоснование: сервер держит статус задачи в Valkey час, а на конвертацию
 * отводит 60 с. Пять минут — страховка от «вечного» статуса queued,
 * когда воркер не запущен.
 */
export const POLL_DEADLINE_MS = 5 * 60 * 1000;

/**
 * Сколько задач отправляется одновременно.
 *
 * Обоснование: ограничитель сервера — ведро с токенами, ёмкость `RATE_BURST`
 * (20 запросов), пополнение `RATE_PER_SEC` (5 в секунду). Пауза между стартами
 * задаёт скорость: две одновременные отправки с интервалом 400 мс дают
 * 2,5 запроса в секунду, опрос статусов добавляет ещё около 0,7 — итого
 * порядка 3,2 запроса в секунду против пяти устойчивых. Запас полуторакратный,
 * а всплеск в 20 запросов покрывает старт пакета.
 *
 * Раньше на маршруте конвертации ограничитель был навешан дважды, и один POST
 * списывал две единицы бюджета. Дублирование убрано вместе с переездом на
 * NestJS, поэтому оценка выше — про фактический расход.
 *
 * Если `RATE_PER_SEC` будет понижен, эти значения придётся пересчитать:
 * при трёх запросах в секунду пакетная отправка упрётся в лимит.
 */
export const BATCH_CONCURRENCY = 2;

/** Минимальная пауза между запусками отправок (мс). */
export const BATCH_MIN_INTERVAL_MS = 400;

/**
 * Размер порции идентификаторов в пакетном запросе статусов.
 *
 * Обоснование: идентификатор задачи — 36 символов, при 40 идентификаторах
 * длина URL остаётся в пределах безопасных двух килобайт. Сервер читает всю
 * пачку одной командой MGET, поэтому цена запроса от размера порции не растёт —
 * растёт только длина URL.
 */
export const STATUS_BATCH_SIZE = 40;

/**
 * Сколько порций статусов запрашивается одновременно.
 *
 * Обоснование: 2 — прежний лимитер отправки. Раньше порции уходили все разом
 * (`Promise.all` без ограничения): при тысяче активных задач это 25
 * одновременных HTTP-запросов, которые упираются в ограничитель частоты
 * на сервере и получают 429 — после чего поллер уходит в backoff до 40 секунд.
 */
export const STATUS_CONCURRENCY = 2;
