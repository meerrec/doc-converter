/**
 * Лимиты и таймауты браузерного пути — с обоснованием у каждого числа.
 *
 * Почему не из `packages/config`: тот пакет читает `process.env` на верхнем
 * уровне модуля, а в браузере `process` не существует — импорт сломал бы
 * страницу. Лимиты сервера и браузера к тому же измеряются в разных
 * величинах: на сервере это память реплики и SLA конвертации, здесь —
 * память вкладки пользователя и терпение человека перед экраном.
 *
 * Все комментарии на русском языке.
 */

/**
 * Потолок входного файла для браузерного пути.
 *
 * 32 МиБ — оценка, а не замер. Отправная точка: серверный потолок (100 МиБ)
 * рассчитан на реплику с памятью в гигабайты, а здесь распоряжается память
 * вкладки пользователя, и документ занимает в ней в разы больше собственного
 * размера. 32 МиБ выбраны как значение, при котором обработка укладывается
 * в память вкладки с запасом.
 *
 * Уточнить замером при первом же прогоне на крупных книгах.
 */
export const MAX_FILE_BYTES = 32 * 1024 * 1024;

/**
 * Минимальный осмысленный размер PDF на выходе.
 *
 * 32 байта — заголовок `%PDF-` и минимальная структура. Правило то же, что
 * на сервере (`MIN_OUTPUT_BYTES` в `packages/config`): экспортёр, вернувший
 * пустой файл, не должен выдаваться за результат. Число повторено, а не
 * импортировано, по причине из шапки файла.
 */
export const MIN_OUTPUT_BYTES = 32;

/**
 * Разрешение логических координат движка.
 *
 * 96 dpi — не выбор, а свойство печатного display list: `printDisplayList`
 * считает координаты именно в этих пикселях, и `PrintMetrics` принимает
 * метрики шрифта в них же. Перевод в пункты PDF (72/96) делает экспортёр.
 */
export const PRINT_DPI = 96;

/**
 * Кегль шрифта «Normal» книги, если он не задан.
 *
 * 11 pt — умолчание Excel для новой книги; тем же значением пользуется
 * LibreOffice, когда в `styles.xml` шрифта нет. Число нужно метрикам печати:
 * от кегля зависит ширина символа, а от неё — ширины колонок.
 */
export const EXCEL_DEFAULT_FONT_SIZE_PT = 11;

/**
 * Высота строки по умолчанию, если книга её не задала.
 *
 * 15 pt — умолчание Excel для 11 pt: строка вмещает текст с запасом
 * на выносные элементы. Берётся только тогда, когда в листе нет
 * `sheetFormatPr@defaultRowHeight`.
 */
export const EXCEL_DEFAULT_ROW_HEIGHT_PT = 15;

/**
 * Предельный объём картинок книги, которые попадают в PDF.
 *
 * 16 МиБ — потолок входного файла для браузерного пути делится надвое:
 * распакованная картинка занимает в памяти вкладки больше, чем сжатая,
 * а конвертация идёт поверх уже загруженного архива. Медиа сверх предела
 * пропускается поштучно, книга при этом собирается целиком.
 */
export const MAX_MEDIA_BYTES = 16 * 1024 * 1024;

/**
 * Потолок масштаба растра предпросмотра.
 *
 * 3 — запас над плотностью экранов: у типичного ноутбука `devicePixelRatio`
 * равен 2, и множитель нужен лишь затем, чтобы увеличенная страница осталась
 * резкой. Растр — это память вкладки, а не файл: страница A4 при масштабе 3
 * занимает около 45 МБ, и выше этого предела панель показывает не резче,
 * а медленнее.
 */
export const PREVIEW_MAX_SCALE = 3;

/**
 * Предельная площадь растра одной страницы предпросмотра.
 *
 * 12 Мпикс — примерно 2900×4100: это A4 при масштабе около 3, то есть
 * потолок выше почти никогда не срабатывает на обычной бумаге, но ловит
 * страницу необычного формата. Память одного растра при этом ограничена
 * 48 МБ (четыре байта на пиксель), и она не зависит от того, сколько
 * страниц в документе.
 */
export const PREVIEW_MAX_PAGE_PIXELS = 12_000_000;

/**
 * Предельное число пикселей одной картинки.
 *
 * 40 МП — примерно 8000×5000: этого хватает фотографии с запасом, а дальше
 * распаковка в память вкладки (четыре байта на пиксель) обойдётся дороже,
 * чем сама конвертация. Картинка сверх предела пропускается.
 */
export const MAX_MEDIA_PIXELS = 40_000_000;
