/**
 * Пути файлов в файловой системе сборки.
 *
 * Путь уникален для каждой задачи, и это не мелочь: офис держит открытым
 * не более одного документа, а переиспользует его **по пути** (см.
 * `bridge/office.ts`). Пока страница писала все файлы в один `/tmp/source.xlsx`,
 * предпросмотр одной книги и конвертация другой молча работали с первой:
 * файл перезаписывался, а открытый документ оставался прежним.
 *
 * Расширение приходит типом `BrowserFormat`, а не строкой из имени файла:
 * так в путь физически не может попасть ничего пользовательского — ни имени,
 * ни каталога, ни `..`. Остальное имя пути — счётчик, и он же не даёт двум
 * задачам с одним файлом занять один путь.
 *
 * Все комментарии на русском языке.
 */

import { FS_TMP_DIR } from './constants.js';
import type { BrowserFormat } from './filters.js';

/** Готовый PDF: имя постоянное — экспортёр пишет по этому пути из задания. */
export const OUTPUT_PATH = `${FS_TMP_DIR}/result.pdf`;

/**
 * Счётчик задач.
 *
 * Сбрасывается вместе со страницей — этого достаточно: пути нужны уникальными
 * в пределах одной вкладки, а не между сессиями.
 */
let counter = 0;

/**
 * Выдаёт путь для исходного файла следующей задачи.
 *
 * @param format - формат документа
 * @returns путь в файловой системе сборки
 */
export function nextSourcePath(format: BrowserFormat): string {
  counter += 1;

  return `${FS_TMP_DIR}/source-${counter}.${format}`;
}
