/**
 * Ленивая загрузка движка.
 *
 * Модуль существует ради размера страницы: движок весит мегабайты (wasm
 * вёрстки, шрифты, разбор OOXML), и статический импорт положил бы его
 * в основной бандл — то есть в загрузку каждого посетителя, включая тех,
 * кто пользуется только серверным маршрутом. Динамический импорт оставляет
 * движок отдельным чанком, который браузер берёт при первой задаче.
 *
 * Грузится именно клиент: в браузере он поднимает воркер, и сам код движка
 * на главный поток не попадает вовсе. Работу выполняет воркер, а `warmup`
 * отделяет её самое долгое место — инициализацию wasm — от конвертации,
 * чтобы страница показывала его своей фазой.
 *
 * Промис мемоизирован: чанк грузится один раз, и, если он не загрузился,
 * повторять попытку в этой же вкладке незачем — браузер уже отбросил модуль,
 * а второй запрос тех же мегабайт выглядел бы как зависание.
 *
 * Все комментарии на русском языке.
 */

import type { OfficeClient } from './client.js';

/** Точка входа движка: клиент воркера. */
export type EngineModule = OfficeClient;

/** Начатая загрузка: одна на документ. */
let pending: Promise<EngineModule> | null = null;

/**
 * Отдаёт клиент движка, загружая его при первом обращении.
 *
 * @returns клиент движка
 */
export function loadEngine(): Promise<EngineModule> {
  pending ??= import('./client.js').then((module) => module.getOfficeClient());

  return pending;
}
