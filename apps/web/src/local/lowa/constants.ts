/**
 * Лимиты и таймауты браузерного пути — с обоснованием у каждого числа.
 *
 * Почему не из `packages/config`: тот пакет читает `process.env` на верхнем
 * уровне модуля, а в браузере `process` не существует — импорт сломал бы
 * страницу. Лимиты сервера и браузера к тому же измеряются в разных
 * величинах: на сервере это память реплики и SLA конвертации, здесь —
 * память вкладки пользователя и терпение человека перед экраном.
 *
 * Все комментарии на русском языке.
 */

/**
 * Ожидание готовности сборки после загрузки файлов.
 *
 * 120 с — загрузка 53 МБ идёт отдельным шагом (с прогрессом), а этот таймаут
 * относится только к инициализации модуля и старту UNO: на проверке это
 * занимало секунды. Запас нужен машинам без аппаратного ускорения WASM
 * (компиляция модуля там идёт заметно дольше). Таймаут ловит зависание,
 * а не медленный канал: скачивание под него не попадает.
 */
export const BOOT_TIMEOUT_MS = 120_000;

/**
 * Таймаут одной операции — загрузки документа или экспорта PDF.
 *
 * 300 с — серверный таймаут (120 с) рассчитан на нативный LibreOffice и для
 * сборки в WASM мал: она медленнее нативной в разы, а книга на десятки листов
 * с изображениями импортируется здесь десятками секунд. Значение — защита
 * от бесконечного зависания, а не обещание уложиться: страница показывает
 * прогресс и позволяет отменить операцию.
 */
export const OPERATION_TIMEOUT_MS = 300_000;

/**
 * Потолок входного файла для браузерного пути.
 *
 * 32 МиБ — оценка, а не замер. Отправная точка: серверный потолок (100 МиБ)
 * рассчитан на реплику с памятью в гигабайты, а здесь распоряжается линейная
 * память сборки — 1 ГБ (измерено), и документ занимает в ней в разы больше
 * собственного размера. 32 МиБ выбраны как значение, при котором импорт
 * укладывается в этот потолок с запасом.
 *
 * Уточнить замером при первом же прогоне на крупных книгах — вместе
 * с проверкой памяти в `docs/local-wasm.md`.
 */
export const MAX_FILE_BYTES = 32 * 1024 * 1024;

/**
 * Минимальный осмысленный размер PDF на выходе.
 *
 * 32 байта — заголовок `%PDF-` и минимальная структура. Правило то же, что
 * на сервере (`MIN_OUTPUT_BYTES` в `packages/config`): экспортёр, вернувший
 * пустой файл, не должен выдаваться за результат. Число повторено, а не
 * импортировано, по причине из шапки файла.
 */
export const MIN_OUTPUT_BYTES = 32;

/**
 * Каталог виртуальной файловой системы для рабочих файлов.
 *
 * `/tmp` — единственный каталог, который в сборке заведомо есть и доступен
 * на запись: домашний каталог в образ файловой системы не заводится.
 */
export const FS_TMP_DIR = '/tmp';
