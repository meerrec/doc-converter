import { defineConfig } from 'vite';

/**
 * Сборка моста — скрипта, который сборка LibreOffice исполняет в своём воркере.
 *
 * Отдельный конфиг, а не общий с приложением, по двум причинам:
 *
 * - **формат**. Сборка подключает скрипт через `importScripts`, то есть
 *   классическим скриптом, а не модулем: нужен IIFE, а не ESM. Основная
 *   сборка приложения — модульная, и совместить это в одном конфиге нельзя;
 * - **место**. Мост не является частью интерфейса и не должен попадать
 *   в `dist/assets`: там его подхватил бы SPA-fallback, а потолок размера
 *   бандла в CI считает файлы по маске — второй скрипт сломал бы подсчёт.
 *
 * Каталог `dist/local` в основную сборку не входит: `vite build` чистит
 * `dist` перед сборкой, поэтому мост собирается **после** приложения
 * (см. скрипт `build` в `package.json`).
 */
export default defineConfig({
  build: {
    outDir: 'dist/local',
    emptyOutDir: false,
    lib: {
      entry: 'src/local/lowa/bridge/entry.ts',
      formats: ['iife'],
      name: 'LowaBridge',
      fileName: () => 'bridge.js',
    },
    target: 'es2022',
    // Минификация выключена намеренно: мост небольшой, а читаемое имя
    // в стеке исключения из воркера стоит дороже сэкономленных килобайт
    minify: false,
    sourcemap: false,
  },
});
