import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';

/**
 * Сборка страницы браузерной конвертации (`/local`).
 *
 * Отдельный конфиг, а не общий с приложением, по трём причинам:
 *
 * - **заголовки изоляции**. Странице нужны `Cross-Origin-Opener-Policy` и
 *   `Cross-Origin-Embedder-Policy`, а интерфейсу сервиса они вредны: вместе
 *   с изоляцией перестали бы открываться ссылки на результаты в MinIO.
 *   Значит это разные документы, а не разделы одного;
 * - **потолок бандла**. `ci.yml` считает размер по маске `dist/assets/*.js`
 *   и ждёт ровно один файл — второй скрипт сломал бы подсчёт. Здесь своя
 *   сборка и свой каталог (`dist/local`), и потолок для неё отдельный;
 * - **вес**. Сборка LibreOffice и обвязка UNO не должны попадать в бандл
 *   интерфейса: страница сервиса остаётся прежней.
 *
 * `root` — каталог страницы: Vite кладёт `index.html` относительно него,
 * поэтому файл оказывается в `dist/local/index.html`, а не повторяет путь
 * `src/local/`. Общие компоненты (`../components`) при этом импортируются
 * как обычно: граф модулей строится от входа и выходить за `root` может.
 */
export default defineConfig({
  plugins: [react()],
  root: 'src/local',
  base: '/local/',
  build: {
    outDir: '../../dist/local',
    // Каталог общий с мостом (`bridge.js`): очистка снесла бы его
    emptyOutDir: false,
    sourcemap: false,
  },
});
